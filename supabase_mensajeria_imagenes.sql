-- MENSAJERÍA MX: mensajes + borrar todo + imágenes
-- Antes: Authentication -> Sign In / Providers -> Allow anonymous sign-ins = ON

create table if not exists public.chat_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  username text not null,
  created_at timestamptz not null default now()
);
create unique index if not exists chat_profiles_username_unique
on public.chat_profiles (lower(username));

create table if not exists public.chat_messages (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  username text not null,
  body text,
  image_url text,
  created_at timestamptz not null default now(),
  constraint chat_message_has_content check (
    nullif(trim(coalesce(body,'')),'') is not null or image_url is not null
  )
);

alter table public.chat_messages add column if not exists image_url text;

alter table public.chat_profiles enable row level security;
alter table public.chat_messages enable row level security;

drop policy if exists "chat_profiles_select" on public.chat_profiles;
drop policy if exists "chat_profiles_insert" on public.chat_profiles;
drop policy if exists "chat_messages_select" on public.chat_messages;

create policy "chat_profiles_select" on public.chat_profiles
for select to authenticated using (true);
create policy "chat_profiles_insert" on public.chat_profiles
for insert to authenticated with check (auth.uid() = user_id);
create policy "chat_messages_select" on public.chat_messages
for select to authenticated using (true);

grant select, insert on public.chat_profiles to authenticated;
grant select on public.chat_messages to authenticated;

