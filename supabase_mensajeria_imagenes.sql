-- ENVIAR MENSAJE
create or replace function public.enviar_mensaje(
  p_body text default null,
  p_image_url text default null
)
returns public.chat_messages
language plpgsql
security definer
set search_path=public
as $$
declare
  v_uid uuid;
  v_username text;
  v_body text;
  r public.chat_messages;
begin
  v_uid:=auth.uid();
  if v_uid is null then raise exception 'No hay usuario autenticado.'; end if;
  select username into v_username from public.chat_profiles where user_id=v_uid;
  if v_username is null then raise exception 'No existe el perfil del usuario.'; end if;
  v_body:=nullif(trim(coalesce(p_body,'')), '');
  if v_body is null and p_image_url is null then raise exception 'Mensaje vacío.'; end if;
  if v_body is not null and length(v_body)>1000 then raise exception 'El mensaje supera 1000 caracteres.'; end if;
  insert into public.chat_messages(user_id,username,body,image_url)
  values(v_uid,v_username,v_body,p_image_url)
  returning * into r;
  return r;
end;
$$;
grant execute on function public.enviar_mensaje(text,text) to authenticated;

-- BORRAR TODA LA CONVERSACIÓN
create or replace function public.borrar_conversacion()
returns void
language plpgsql
security definer
set search_path=public
as $$
begin
  if auth.uid() is null then raise exception 'No hay usuario autenticado.'; end if;
  delete from public.chat_messages;
end;
$$;
grant execute on function public.borrar_conversacion() to authenticated;

